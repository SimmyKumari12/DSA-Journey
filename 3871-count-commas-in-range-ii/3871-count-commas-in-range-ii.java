class Solution {
    public long countCommas(long n) {
        if(n < 1000) return 0;
        if(n < 1_000_000) return n-999;
        if(n < 1_000_000_000) return (999_999-999)+((n-999_999)*2);
        if(n < 1_000_000_000_000L) return (999_999-999)+((999_999_999-999_999)*2)+((n-999_999_999)*3);
        if(n < 1_000_000_000_000_000L) return (999_999-999)+((999_999_999-999_999L)*2)+((999_999_999_999L-999_999_999L)*3)+((n-999_999_999_999L)*4);
        if(n < 1_000_000_000_000_000_000L) return (999_999-999)+((999_999_999-999_999)*2)+((999_999_999_999L-999_999_999L)*3)+((999_999_999_999_999L-999_999_999_999L)*4)+((n-999_999_999_999_999L)*5);
        return -1;
    }
}